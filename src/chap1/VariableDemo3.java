package chap1;

public class VariableDemo3 {
    //变量练习三
    public static void main(String[] args){
        //byte
        byte b=10;
        System.out.println(b);
        //short
        short s=20;
        System.out.println(s);
        //long 如果要定义long类型变量，在数值后需要加一个L作为后缀
        long n=9999999L;
        System.out.println(n);
        //定义float类型变量是，数值后需要加一个F作为后缀
        float h=2.111F;
        System.out.println(h);
        //char
        char c='中';
        System.out.println(c);
        //boolean 只能定义为true/flase
        boolean o =true;
        System.out.println(o);

    }
}
